"""Validate Bazel-owned public Protobuf import visibility semantics."""

from __future__ import annotations

import os
import unittest
from pathlib import Path

from score.ecu_model.data_types.common import DataTypeBase
from score.ecu_model.model import ModelRegistry


class ProtobufImportVisibilityIntegrationTest(unittest.TestCase):
    """Test public transitive import behavior through Bazel."""

    def test_given_public_import_chain_when_compiling_then_transitive_symbol_is_resolved(self):
        registry = load_public_import_registry()

        self.assertIn("demo.a.AMessage", registry)
        self.assertIn("demo.c.CMessage", registry)


def load_public_import_registry():
    """Load the registry generated by the Bazel descriptor pipeline."""
    runfiles_root = Path(os.environ["RUNFILES_DIR"])
    output_path = next(runfiles_root.rglob("public_import_model.pkl"))
    ModelRegistry.deserialize(output_path.read_bytes())
    return {
        element.fully_qualified_name: element
        for element in ModelRegistry.elements.values()
        if isinstance(element, DataTypeBase) and element.name is not None
    }


if __name__ == "__main__":
    unittest.main()
